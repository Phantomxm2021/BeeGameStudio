#!/usr/bin/env bash
# Migrates the legacy public schema and public data into an EMPTY new Supabase project.
#
# Required environment variables:
#   OLD_DB_URL, TARGET_DB_PASSWORD, MIGRATION_OUTPUT_DIR,
#   CONFIRM_TARGET_IS_EMPTY=YES
# Optional target settings default to the local Manager-exposed Docker port:
#   TARGET_DB_HOST=127.0.0.1 TARGET_DB_PORT=8008 TARGET_DB_USER=postgres
#   TARGET_DB_NAME=postgres
# Entered connection settings are saved to .beegame-migration.env beside this
# script with mode 600. Set MIGRATION_CONFIG_FILE to use a different location.
#
# This intentionally does not migrate auth users or Storage objects. Do not cut
# production traffic over until those two stages are completed separately.

set -euo pipefail

script_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
baseline_sql="$script_dir/beegame-legacy-schema-baseline.sql"
additions_sql="$script_dir/beegame-post-restore-additions.sql"
migration_config_file="${MIGRATION_CONFIG_FILE:-$script_dir/.beegame-migration.env}"

if [[ -f "$migration_config_file" ]]; then
  [[ ! -L "$migration_config_file" ]] || {
    printf 'Refusing to load symbolic-link config file: %s\n' "$migration_config_file" >&2
    exit 1
  }
  # This file is generated by save_migration_config below with shell-escaped values.
  source "$migration_config_file"
  printf '[CONFIG] Loaded saved connection settings from %s\n' "$migration_config_file"
fi

printf '\n=== BeeGame public database migration ===\n'
printf 'This script will export old public data and restore it into an empty new project.\n'
printf 'The target is the local Manager-exposed PostgreSQL port: 127.0.0.1:8008.\n'
printf 'Database passwords are intentionally hidden when entered.\n\n'

read_secret_if_missing() {
  local variable="$1"
  local prompt="$2"
  local value

  [[ -n "${!variable:-}" ]] && return
  if [[ ! -t 0 ]]; then
    printf 'Missing required environment variable: %s\n' "$variable" >&2
    exit 1
  fi

  printf '[INPUT] %s\n' "$prompt"
  printf 'Paste the value now (hidden) and press Enter: '
  read -r -s value
  printf '\n'
  [[ -n "$value" ]] || {
    printf '%s cannot be empty.\n' "$variable" >&2
    exit 1
  }
  printf -v "$variable" '%s' "$value"
  export "$variable"
}

read_value_if_missing() {
  local variable="$1"
  local prompt="$2"
  local value

  [[ -n "${!variable:-}" ]] && return
  if [[ ! -t 0 ]]; then
    printf 'Missing required environment variable: %s\n' "$variable" >&2
    exit 1
  fi

  printf '[INPUT] %s\n' "$prompt"
  printf 'Enter the value and press Enter: '
  read -r value
  [[ -n "$value" ]] || {
    printf '%s cannot be empty.\n' "$variable" >&2
    exit 1
  }
  printf -v "$variable" '%s' "$value"
  export "$variable"
}

save_migration_config() {
  umask 077
  {
    printf '%s\n' '# Generated by migrate-old-public-to-new.sh. Keep this file private.'
    printf 'OLD_DB_URL=%q\n' "$OLD_DB_URL"
    printf 'TARGET_DB_HOST=%q\n' "$TARGET_DB_HOST"
    printf 'TARGET_DB_PORT=%q\n' "$TARGET_DB_PORT"
    printf 'TARGET_DB_USER=%q\n' "$TARGET_DB_USER"
    printf 'TARGET_DB_NAME=%q\n' "$TARGET_DB_NAME"
    printf 'TARGET_DB_PASSWORD=%q\n' "$TARGET_DB_PASSWORD"
    printf 'MIGRATION_OUTPUT_DIR=%q\n' "$MIGRATION_OUTPUT_DIR"
  } > "$migration_config_file"
  chmod 600 "$migration_config_file"
  printf '[CONFIG] Saved connection settings to %s (permissions: 600).\n' "$migration_config_file"
}

read_secret_if_missing OLD_DB_URL 'Old source PostgreSQL URL (postgresql://user:password@host:port/database)'
case "$OLD_DB_URL" in
  postgres://*|postgresql://*) ;;
  *)
    printf 'OLD_DB_URL must start with postgres:// or postgresql://. It is the old SOURCE database URI, not a password or a database name.\n' >&2
    exit 1
    ;;
esac
TARGET_DB_HOST="${TARGET_DB_HOST:-127.0.0.1}"
TARGET_DB_PORT="${TARGET_DB_PORT:-8008}"
TARGET_DB_USER="${TARGET_DB_USER:-postgres}"
TARGET_DB_NAME="${TARGET_DB_NAME:-postgres}"
read_secret_if_missing TARGET_DB_PASSWORD "Password for local target ${TARGET_DB_USER}@${TARGET_DB_HOST}:${TARGET_DB_PORT}/${TARGET_DB_NAME}"
read_value_if_missing MIGRATION_OUTPUT_DIR 'Directory for the exported public data'
save_migration_config

if [[ "${CONFIRM_TARGET_IS_EMPTY:-}" != "YES" ]]; then
  if [[ ! -t 0 ]]; then
    printf 'Refusing to write to the new database. Set CONFIRM_TARGET_IS_EMPTY=YES after confirming it is the new, empty project.\n' >&2
    exit 1
  fi
  printf '[CONFIRM] The new target project must contain no BeeGame tables.\n'
  printf 'Type YES to confirm it is empty: '
  read -r CONFIRM_TARGET_IS_EMPTY
  [[ "$CONFIRM_TARGET_IS_EMPTY" == "YES" ]] || {
    printf 'Migration cancelled.\n' >&2
    exit 1
  }
fi

for command in sudo npx psql tee; do
  command -v "$command" >/dev/null 2>&1 || {
    printf 'Missing required command: %s\n' "$command" >&2
    exit 1
  }
done

supabase_cli() {
  sudo npx --yes supabase "$@"
}

source_postgres_cli() {
  sudo env "PGCONNECT_TIMEOUT=${PGCONNECT_TIMEOUT:-15}" psql "$@"
}

target_postgres_cli() {
  sudo env \
    "PGCONNECT_TIMEOUT=${PGCONNECT_TIMEOUT:-15}" \
    "PGPASSWORD=$TARGET_DB_PASSWORD" \
    psql \
      --host "$TARGET_DB_HOST" \
      --port "$TARGET_DB_PORT" \
      --username "$TARGET_DB_USER" \
      --dbname "$TARGET_DB_NAME" \
      "$@"
}

step() {
  printf '[%s] %s\n' "$(date '+%Y-%m-%d %H:%M:%S')" "$*"
}

run_with_progress() {
  local description="$1"
  shift
  local pid monitor result_code

  step "$description"
  "$@" &
  pid=$!
  (
    while sleep 15; do
      kill -0 "$pid" 2>/dev/null || exit 0
      step "$description — still running"
    done
  ) &
  monitor=$!

  set +e
  wait "$pid"
  result_code=$?
  set -e
  kill "$monitor" 2>/dev/null || true
  wait "$monitor" 2>/dev/null || true

  if [[ "$result_code" -ne 0 ]]; then
    step "$description — FAILED (exit $result_code)"
    return "$result_code"
  fi
  step "$description — completed"
}

for file in "$baseline_sql" "$additions_sql"; do
  [[ -s "$file" ]] || {
    printf 'Required SQL file is missing or empty: %s\n' "$file" >&2
    exit 1
  }
done

mkdir -p "$MIGRATION_OUTPUT_DIR"
data_sql="$MIGRATION_OUTPUT_DIR/old-server-public-data.sql"
log_file="$MIGRATION_OUTPUT_DIR/migrate-old-public-to-new.log"
exec > >(tee -a "$log_file") 2>&1

step "Log file: $log_file"
step 'Requesting sudo authorization...'
sudo -v
step 'Sudo authorization granted.'

run_with_progress 'Testing old database connection' source_postgres_cli \
  --dbname "$OLD_DB_URL" \
  --no-psqlrc \
  --variable ON_ERROR_STOP=1 \
  --command "select 'old database connected' as status, current_database() as database_name;"

run_with_progress "Testing new local database connection at ${TARGET_DB_HOST}:${TARGET_DB_PORT}" target_postgres_cli \
  --no-psqlrc \
  --variable ON_ERROR_STOP=1 \
  --command "select 'new database connected' as status, current_database() as database_name;"

empty_check_output="$(mktemp "$MIGRATION_OUTPUT_DIR/.target-empty-check.XXXXXX")"
run_with_progress "Checking that the new target has no BeeGame tables (PostgreSQL connection timeout: ${PGCONNECT_TIMEOUT:-15}s)" target_postgres_cli \
  --no-psqlrc \
  --tuples-only \
  --no-align \
  --output "$empty_check_output" \
  --command "select count(*) from information_schema.tables where table_schema = 'public' and table_name ~ '^beegame_';"
existing_beegame_tables="$(tr -d '[:space:]' < "$empty_check_output")"
rm -f "$empty_check_output"
step "Target empty-check found ${existing_beegame_tables} BeeGame table(s)."

if [[ "$existing_beegame_tables" != "0" ]]; then
  printf 'The target already contains %s BeeGame public table(s). Use a clean new project; this script never drops target data.\n' "$existing_beegame_tables" >&2
  exit 1
fi
step 'New target is empty.'

run_with_progress 'Exporting old public data' supabase_cli db dump \
  --db-url "$OLD_DB_URL" \
  --schema public \
  --data-only \
  --use-copy \
  --file "$data_sql"

run_with_progress 'Restoring legacy-compatible public schema and data' target_postgres_cli \
  --no-psqlrc \
  --single-transaction \
  --variable ON_ERROR_STOP=1 \
  --file "$baseline_sql" \
  --command 'SET session_replication_role = replica' \
  --file "$data_sql"

run_with_progress 'Adding worktree-only database contracts' target_postgres_cli \
  --no-psqlrc \
  --single-transaction \
  --variable ON_ERROR_STOP=1 \
  --file "$additions_sql"

step 'Verifying restored database contracts...'
verified="$({
  target_postgres_cli --no-psqlrc --tuples-only --no-align --command "
    select case when
      to_regclass('public.beegame_storage_quota_policies') is not null
      and exists (
        select 1 from information_schema.columns
        where table_schema = 'public'
          and table_name = 'beegame_storage_objects'
          and column_name = 'purge_after'
      )
      and to_regclass('public.beegame_confirmed_brief_revisions') is not null
      and to_regclass('public.beegame_confirmed_brief_heads') is not null
      and to_regclass('public.beegame_credit_accounts') is not null
      and to_regclass('public.beegame_credit_ledger') is not null
    then 'ok' else 'failed' end;"
} | tr -d '[:space:]')"

[[ "$verified" == "ok" ]] || {
  printf 'Post-restore verification failed; do not switch traffic.\n' >&2
  exit 1
}
step 'Database contract verification passed.'

printf '\nPUBLIC DATABASE STAGE COMPLETE.\n'
printf 'Data export retained at: %s\n' "$data_sql"
printf 'Before switching traffic, separately migrate auth users and Storage files.\n'
